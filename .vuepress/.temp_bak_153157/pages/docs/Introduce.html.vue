<h2 id="original-intent" tabindex="-1"><a class="header-anchor" href="#original-intent"><span>Original Intent</span></a></h2>
<p>For most researchers in geoscience or meteorology, data processing is a massive undertaking, often taking hours or even days. Without proper tools or methods, it becomes extremely challenging to handle multi-temporal datasets (e.g., time-series remote sensing data) or large-scale studies (e.g., national-level analysis).</p>
<p>Thus, the original purpose of building gma was to <em><strong>address these challenges</strong></em>. As the library has evolved through successive versions, its capabilities have grown increasingly rich and robust, enabling it to solve an ever-widening range of problems.</p>
